"""API ORANGE (CALYPSO) — client protégé + synchronisation « outbox ».

Gestion des limites de débit et des pannes :
* ``TokenBucket`` (débit moyen + rafale) devant CHAQUE appel, ``Semaphore`` de concurrence, ``CircuitBreaker``
  (ouvert après N échecs consécutifs), HTTP 429 → ``Retry-After`` honoré pour tous les threads ;
* délais séparés connexion/lecture ; ``requests.Session`` avec pool de connexions ; vérification TLS activée ;
* jeton OAuth2 partagé, renouvelé par UN seul thread (verrou) et invalidé sur 401 ;
* nouvelles tentatives : seulement timeouts / 5xx / 429, délai exponentiel avec gigue stocké EN BASE
  (``orange_next_retry_at``) — survit aux redémarrages, aucune tâche en mémoire.

Découplage : la détection n'appelle JAMAIS Orange. Elle écrit le ticket (état ``pending``) ; ``sync_outbox`` (job
périodique) crée les tickets chez Orange puis restaure ceux qui ont été fermés localement (``close_pending``).
"""
from __future__ import annotations

import threading
import time
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from collections.abc import Callable

import requests
from requests.adapters import HTTPAdapter

from . import ticket_log, tickets
from .config import fmt, now_local, parse, settings
from .logger import get_logger
from .ratelimit import CircuitBreaker, TokenBucket, backoff_delay

logger = get_logger(__name__)

# Valeurs métier de l'API Orange (centralisées ici ; l'identifiant de ressource vient de l'environnement)
TICKET_TYPE = {"id": "1", "label": "Incident"}
ORIGIN = {"id": "J", "label": "Incident"}
RESTORE_CAUSE = [{"problemDetail": {"id": "315677", "label": "Alarm defect"},
                  "problemCategory": {"id": "107", "label": "Degraded Service"}}]
DESCRIPTION_MAX = 2500


@dataclass
class Result:
    ok: bool
    orange_id: str | None = None
    retryable: bool = False
    retry_after: float | None = None
    ambiguous: bool = False            # requête peut-être traitée côté Orange (timeout après envoi)
    error: str = ""
    data: dict | None = None


def format_description(ticket: dict) -> str:
    sep = "=" * 50
    return "\n".join(["AUTODO Network Monitoring Alert", sep, str(ticket.get("description", "")), sep,
                      "Generated by AUTODO Monitoring System", f"AUTODO ticket: {ticket.get('id')}",
                      f"Timestamp: {ticket.get('timestamp')}"])[:DESCRIPTION_MAX]


class OrangeClient:
    def __init__(self, session: requests.Session | None = None, bucket: TokenBucket | None = None,
                 breaker: CircuitBreaker | None = None):
        s = settings
        self.base = f"{s.orange_server}{s.orange_base_endpoint}/troubleTicket"
        self.token_url = f"{s.orange_server}{s.orange_token_endpoint}"
        self.verify = s.orange_ca_bundle or s.orange_verify_tls
        self.timeout = (s.orange_connect_timeout, s.orange_read_timeout)
        self.bucket = bucket or TokenBucket(s.orange_rate_per_s, s.orange_burst)
        self.breaker = breaker or CircuitBreaker(s.orange_breaker_threshold, s.orange_breaker_cooldown)
        self.slots = threading.BoundedSemaphore(max(1, s.orange_max_concurrency))
        self.session = session or requests.Session()
        if session is None:
            self.session.mount("https://", HTTPAdapter(pool_connections=2, pool_maxsize=max(2, s.orange_max_concurrency)))
            self.session.mount("http://", HTTPAdapter(pool_connections=2, pool_maxsize=max(2, s.orange_max_concurrency)))
        self._token: str | None = None
        self._token_exp = 0.0
        self._token_lock = threading.Lock()

    @property
    def configured(self) -> bool:
        return bool(settings.orange_server and settings.orange_client_id and settings.orange_client_secret)

    # ------------------------------------------------------------------ jeton
    def _get_token(self, force: bool = False) -> str | None:
        with self._token_lock:                       # un seul thread renouvelle, les autres réutilisent
            if not force and self._token and time.monotonic() < self._token_exp - 60:
                return self._token
            if not self.bucket.acquire(timeout=30):
                return None
            try:
                r = self.session.post(self.token_url, data={"grant_type": "client_credentials"},
                                      auth=(settings.orange_client_id, settings.orange_client_secret),
                                      headers={"Accept": "application/json"}, timeout=self.timeout, verify=self.verify)
                if r.status_code == 200:
                    d = r.json()
                    self._token = d.get("access_token")
                    self._token_exp = time.monotonic() + float(d.get("expires_in", 3600))
                    return self._token
                logger.warning("Orange: jeton refusé (HTTP %s)", r.status_code)
            except requests.RequestException as e:
                logger.warning("Orange: jeton indisponible (%s)", type(e).__name__)
            self._token = None
            return None

    # ------------------------------------------------------------------ requête protégée
    def _call(self, method: str, url: str, *, json: dict | None = None, headers: dict | None = None,
              params: dict | None = None, _retry_auth: bool = True) -> Result:
        if not self.breaker.allow():
            return Result(False, retryable=True, error="circuit ouvert (API Orange indisponible)")
        token = self._get_token()
        if not token:
            self.breaker.failure()
            return Result(False, retryable=True, error="jeton OAuth indisponible")
        if not self.bucket.acquire(timeout=30):
            return Result(False, retryable=True, error="limite de débit locale atteinte")
        h = {"Authorization": f"Bearer {token}", "Content-Type": "application/json;charset=utf-8",
             "Accept-Language": "en", "X-Client-User-Id": settings.orange_cuid, **(headers or {})}
        sent = False
        try:
            with self.slots:
                sent = True
                r = self.session.request(method, url, json=json, headers=h, params=params,
                                         timeout=self.timeout, verify=self.verify)
        except requests.ConnectTimeout as e:                       # rien n'est parti : sûr de réessayer
            self.breaker.failure()
            return Result(False, retryable=True, error=f"connect timeout: {e}")
        except requests.RequestException as e:
            self.breaker.failure()
            return Result(False, retryable=True, ambiguous=sent and method == "POST", error=f"{type(e).__name__}: {e}")

        code = r.status_code
        if code == 401 and _retry_auth:
            self._get_token(force=True)
            return self._call(method, url, json=json, headers=headers, params=params, _retry_auth=False)
        if code == 429:
            wait = _retry_after(r) or 30.0
            self.bucket.pause_for(wait)                              # gèle tous les appelants
            return Result(False, retryable=True, retry_after=wait, error="HTTP 429 (limite Orange)")
        if code >= 500:
            self.breaker.failure()
            return Result(False, retryable=True, ambiguous=method == "POST", error=f"HTTP {code}")
        if code >= 400:                                              # erreur client : inutile de réessayer
            self.breaker.success()
            return Result(False, retryable=False, error=f"HTTP {code}: {r.text[:200]}")
        self.breaker.success()
        try:
            data = r.json() if r.content else {}
        except ValueError:
            data = {}
        return Result(True, data=data if isinstance(data, dict) else {"items": data})

    # ------------------------------------------------------------------ opérations
    def create_ticket(self, ticket: dict) -> Result:
        payload = {"description": format_description(ticket), "ticketType": TICKET_TYPE, "origin": ORIGIN}
        if settings.orange_related_resource_id:
            payload["relatedResource"] = {"referredResource": False, "id": settings.orange_related_resource_id,
                                          "resourceSpecCharacteristic": [{"index": "1", "value": "ResourceId1"}]}
        res = self._call("POST", self.base, json=payload)
        if res.ok:
            oid = (res.data or {}).get("id") or (res.data or {}).get("ticketId")
            if not oid:
                return Result(False, retryable=False, ambiguous=True, error="réponse sans identifiant de ticket")
            res.orange_id = str(oid)
        return res

    def find_by_external_id(self, autodo_id: int) -> str | None:
        """Si l'API le permet : retrouve un ticket déjà créé (anti-doublon après réponse perdue)."""
        res = self._call("GET", self.base, params={"externalId": str(autodo_id)})
        items = (res.data or {}).get("items") or ([res.data] if res.data and res.data.get("id") else [])
        return str(items[0]["id"]) if res.ok and items else None

    def get_status(self, orange_id: str) -> Result:
        res = self._call("GET", f"{self.base}/{orange_id}")
        if res.ok:
            entries = (res.data or {}).get("status", []) or []
            current = next((e.get("code") for e in entries if str(e.get("isCurrentStatus")).lower() == "true"), None)
            res.data = {"current": current, "entries": entries}
        return res

    def restore(self, orange_id: str) -> Result:
        payload = {"status": {"code": "Restored", "isCurrentStatus": "true",
                              "startDate": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")},
                   "troubleCause": RESTORE_CAUSE}
        return self._call("PUT", f"{self.base}/{orange_id}", json=payload, headers={"X-HTTP-Method-Override": "PATCH"})

    def add_note(self, orange_id: str, message: str, author: str = "AUTODO", when: datetime | None = None) -> Result:
        """Ajoute une note au ticket distant (PUT + ``X-HTTP-Method-Override: PATCH``).

        ⚠ FORMAT À CONFIRMER avec l'API Orange réelle : corps ``{"note": [{"text", "author", "date"}]}`` supposé.
        Toute adaptation du format se fait ICI, nulle part ailleurs.
        """
        stamp = (when or datetime.now(timezone.utc)).strftime("%Y-%m-%dT%H:%M:%SZ")
        payload = {"note": [{"text": message[:2000], "author": author, "date": stamp}]}
        return self._call("PUT", f"{self.base}/{orange_id}", json=payload, headers={"X-HTTP-Method-Override": "PATCH"})

    def test_connection_light(self) -> dict:
        """État sans appel réseau (pour /api/status)."""
        return {"configured": self.configured, "breaker": self.breaker.state}

    def test_connection(self) -> dict:
        ok = bool(self._get_token(force=True))
        return {"configured": self.configured, "token_ok": ok, "breaker": self.breaker.state}


def _retry_after(r: requests.Response) -> float | None:
    v = r.headers.get("Retry-After")
    if not v:
        return None
    try:
        return max(0.0, float(v))
    except ValueError:
        return None


