# SYNCHRONISATION (jobs périodiques)
# ============================================================================
def _schedule_retry(t: dict, res: Result, now: str, new_state: str, on_failed: Callable | None = None) -> None:
    attempts = int(t.get("orange_attempts") or 0) + 1
    if not res.retryable or attempts >= settings.orange_max_attempts:
        tickets.update_fields(t["id"], {"orange_sync_state": "failed", "orange_attempts": attempts,
                                        "orange_last_error": res.error[:250]})
        logger.error("Orange: abandon du ticket %s après %s tentative(s) : %s", t["id"], attempts, res.error)
        ticket_log.log_event(t["id"], "orange_failed", f"Abandon de la synchronisation Orange : {res.error}"[:500])
        if on_failed:
            on_failed(t, res.error)
        return
    delay = res.retry_after if res.retry_after else backoff_delay(attempts)
    tickets.update_fields(t["id"], {
        "orange_sync_state": new_state, "orange_attempts": attempts,
        "orange_next_retry_at": fmt(parse(now) + timedelta(seconds=delay)),
        "orange_last_error": (("ambiguous: " if res.ambiguous else "") + res.error)[:250]})


def sync_outbox(client: OrangeClient, on_failed: Callable | None = None, now: str | None = None) -> dict:
    """Crée les tickets ``pending`` chez Orange puis restaure les ``close_pending``. Lot borné, débit limité."""
    stats = {"created": 0, "restored": 0, "retry": 0, "failed": 0}
    if not client.configured:
        return stats
    now = now or fmt(now_local().replace(tzinfo=None))
    budget = settings.orange_batch_size
    for t in tickets.claim_for_orange(("pending",), budget, now):
        if client.breaker.state == "open":
            break
        oid = None
        if settings.orange_lookup_external_id and str(t.get("orange_last_error") or "").startswith("ambiguous"):
            oid = client.find_by_external_id(t["id"])
        res = Result(True, orange_id=oid) if oid else client.create_ticket(t)
        if res.ok and res.orange_id:
            # si le ticket a été fermé localement entre-temps, l'état « closed » est préservé (condition sur l'état)
            ok = tickets.update_fields(t["id"], {"external_api_ticket_id": res.orange_id, "orange_sync_state": "synced",
                                                 "orange_next_retry_at": None, "orange_last_error": None},
                                       expected_state="pending")
            if not ok:
                tickets.update_fields(t["id"], {"external_api_ticket_id": res.orange_id})
            ticket_log.log_event(t["id"], "orange_created", f"Ticket créé chez Orange : {res.orange_id}")
            stats["created"] += 1
        else:
            _schedule_retry(t, res, now, "pending", on_failed)
            stats["retry" if res.retryable else "failed"] += 1
    for t in tickets.claim_for_orange(("close_pending",), budget, now):
        if client.breaker.state == "open":
            break
        res = client.restore(t["external_api_ticket_id"])
        if res.ok:
            tickets.update_fields(t["id"], {"orange_sync_state": "closed", "orange_next_retry_at": None, "orange_last_error": None})
            ticket_log.log_event(t["id"], "orange_restored", f"Ticket {t['external_api_ticket_id']} restauré chez Orange")
            stats["restored"] += 1
        else:
            _schedule_retry(t, res, now, "close_pending", on_failed)
            stats["retry" if res.retryable else "failed"] += 1
    if any(stats.values()):
        logger.info("Orange sync: %s", stats)
    return stats


def sync_notes(client: OrangeClient, limit: int = 20) -> dict:
    """Envoie à Orange les notes en attente (``ticket_events.to_orange``) des tickets DÉJÀ créés chez Orange.

    * ticket pas encore créé chez Orange (``pending`` / ``held``) : la note attend ;
    * ticket fermé, supprimé, jamais envoyé ou abandonné : la note n'a plus d'objet, on la marque traitée ;
    * erreur définitive (4xx) : marquée traitée (pas de boucle infinie) ; erreur temporaire : réessayée au prochain passage.
    """
    stats = {"sent": 0, "waiting": 0, "dropped": 0, "retry": 0}
    if not client.configured:
        return stats
    for note in ticket_log.unsent_orange_notes(limit):
        state, orange_id = note["orange_sync_state"], note["external_api_ticket_id"]
        if note["status"] != "open" or state in ("skipped", "failed", "closed", "close_pending"):
            ticket_log.mark_note_sent(note["id"])
            stats["dropped"] += 1
            continue
        if state != "synced" or not orange_id:
            stats["waiting"] += 1
            continue
        if client.breaker.state == "open":
            break
        result = client.add_note(orange_id, note["message"])
        if result.ok:
            ticket_log.mark_note_sent(note["id"])
            stats["sent"] += 1
        elif not result.retryable:
            logger.error("Orange: note refusée pour le ticket %s (%s) — abandonnée", note["ticket_id"], result.error)
            ticket_log.mark_note_sent(note["id"])
            stats["dropped"] += 1
        else:
            stats["retry"] += 1
    if stats["sent"] or stats["dropped"]:
        logger.info("Orange notes: %s", stats)
    return stats


def reconcile(client: OrangeClient, now: str | None = None, max_tickets: int = 50) -> dict:
    """Ferme localement les tickets que Orange a clôturés (liste blanche de statuts terminaux uniquement)."""
    from . import rules
    stats = {"checked": 0, "closed": 0, "unknown": 0}
    if not client.configured:
        return stats
    now = now or fmt(now_local().replace(tzinfo=None))
    for t in tickets.open_with_orange_id()[:max_tickets]:
        if client.breaker.state == "open":
            break
        res = client.get_status(t["external_api_ticket_id"])
        stats["checked"] += 1
        if not res.ok:
            continue
        current = (res.data or {}).get("current")
        if current and current.lower() in settings.orange_terminal_statuses:
            tickets.update_fields(t["id"], {
                "status": "closed", "closure_timestamp": now, "orange_sync_state": "closed",
                "closure_reason": f"Closed from Orange (status: {current})",
                "ttr_seconds": rules.ttr_seconds(t["timestamp"], now)})
            stats["closed"] += 1
        elif current is None:
            stats["unknown"] += 1               # statut absent/inconnu : on ne ferme PAS (ancienne logique trop agressive)
    if stats["closed"]:
        tickets.invalidate_alert_cache()
        logger.info("Orange reconcile: %s", stats)
    return stats
